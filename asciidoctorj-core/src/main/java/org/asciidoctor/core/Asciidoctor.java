    /**
     * Parse the AsciiDoc source input into a {@link Document}.
     *
     * <p>Accepts input as a {@link Path}, {@link InputStream}, {@link Reader}, String or String List. If the input is a
     * file, information about the file (filename, directory name, etc) gets assigned to attributes on the Document
     * object.
     *
     * @param input the AsciiDoc source
     * @param options a Map of options to control processing (default: {}). See {@link Document} for details about
     *            these options.
     * @return the Document
     */
    public static Document load(Object input, Map<String, Object> options) {
        Map<String, Object> loadOptions = options == null ? new LinkedHashMap<>() : new LinkedHashMap<>(options);
        // NOTE unlike Ruby, the logger option doesn't replace the global logger; it's bound to the current scope (and to
        // the document) so concurrent conversions don't share their logger
        if (loadOptions.containsKey("logger")) {
            Logger logger = LoggerManager.resolveLoggerOption(loadOptions.get("logger"));
            loadOptions.put("logger", logger);
            return LoggerManager.callWithLogger(logger, () -> doLoad(input, loadOptions));
        }
        return doLoad(input, loadOptions);
    }

    private static Document doLoad(Object input, Map<String, Object> options) {
        Map<String, Object> attrs = null;
        try {
            Timings timings = (Timings) options.get("timings");
            if (timings != null) {
                timings.start("read");
            }

            attrs = Options.resolveAttributes(options.get("attributes"));

            Object source;
            if (input instanceof Path path) {
                options.put("input_mtime", lastModified(path));
                String inputPath = Helpers.absolutePath(path);
                attrs.put("docfile", inputPath);
                attrs.put("docdir", Helpers.dirname(inputPath));
                String docfilesuffix = Helpers.extname(inputPath);
                attrs.put("docfilesuffix", docfilesuffix);
                attrs.put("docname", Helpers.basename(inputPath, docfilesuffix));
                source = decodeSource(Files.readAllBytes(path));
            } else if (input instanceof InputStream stream) {
                source = decodeSource(stream.readAllBytes());
            } else if (input instanceof Reader reader) {
                StringBuilder buffer = new StringBuilder();
                char[] chars = new char[8192];
                int read;
                while ((read = reader.read(chars)) != -1) {
                    buffer.append(chars, 0, read);
                }
                source = buffer.toString();
            } else if (input instanceof String str) {
                source = str;
            } else if (input instanceof List<?> list) {
                source = new ArrayList<>(list.stream().map(Object::toString).toList());
            } else if (input != null) {
                throw new IllegalArgumentException("unsupported input type: " + input.getClass());
            } else {
                source = null;
            }

            if (timings != null) {
                timings.record("read");
                timings.start("parse");
            }

            options.put("attributes", attrs);
            Document doc = new Document(source, options);
            if (!Boolean.FALSE.equals(options.get("parse"))) {
                doc = doc.parse();
            }

            if (timings != null) {
                timings.record("parse");
            }
            return doc;
        } catch (IOException e) {
            throw new UncheckedIOException(failedToLoadMessage(attrs) + " - " + e.getMessage(), e);
        } catch (RuntimeException e) {
            throw wrapException(e, failedToLoadMessage(attrs) + " - " + e.getMessage());
        }
    }

    /**
     * Wraps the exception in an exception of the same type with the specified message (like Exception#exception in
     * Ruby), falling back to an {@link AsciidoctorException} if the type cannot be instantiated.
     */
    static RuntimeException wrapException(RuntimeException e, String message) {
        try {
            RuntimeException wrapped = e.getClass().getConstructor(String.class).newInstance(message);
            wrapped.initCause(e);
            wrapped.setStackTrace(e.getStackTrace());
            return wrapped;
        } catch (ReflectiveOperationException | IllegalStateException | SecurityException ex) {
            return new AsciidoctorException(message, e);
        }
    }

    /**
     * Parse the AsciiDoc source input into a {@link Document} using the specified {@link Options}.
     *
     * @see #load(Object, Map)
     */
    public static Document load(Object input, Options options) {
        return load(input, options.map());
    }

    public static Document load(Object input) {
        return load(input, Map.of());
    }

    /**
     * Decodes the source using the BOM, if present, or UTF-8.
     *
     * @throws IllegalArgumentException if the source is binary or contains invalid Unicode data
     */
    private static String decodeSource(byte[] bytes) {
        String source = Helpers.decode(bytes, null);
        if (source.indexOf('\uFFFD') >= 0) {
            try {
                Helpers.decodeStrict(bytes);
            } catch (CharacterCodingException e) {
                throw new IllegalArgumentException("source is either binary or contains invalid Unicode data", e);
            }
        }
        return source;
    }

