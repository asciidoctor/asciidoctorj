    private static String readVersion() {
        try (InputStream in = Asciidoctor.class.getResourceAsStream("/org/asciidoctor/asciidoctorj.properties")) {
            if (in != null) {
                Properties properties = new Properties();
                properties.load(in);
                String version = properties.getProperty("version");
                // NOTE the placeholder is not replaced if the resources are not processed by Maven
                if (version != null && !version.startsWith("${")) {
                    return version;
                }
            }
        } catch (IOException e) {
            // fall through
        }
        return "unknown";
    }

    private static String resolveUserHome() {
        String home = System.getProperty("user.home");
        if (home == null || home.isEmpty()) {
            home = System.getenv("HOME");
        }
        return home == null ? Helpers.workingDirectory() : home;
    }

    @SafeVarargs
    private static <T> Set<T> orderedSet(T... values) {
        return java.util.Collections.unmodifiableSet(new LinkedHashSet<>(List.of(values)));
    }

    private static Map<String, String> orderedMap(String... keyValues) {
        Map<String, String> map = new LinkedHashMap<>();
        for (int i = 0; i < keyValues.length; i += 2) {
            map.put(keyValues[i], keyValues[i + 1]);
        }
        return java.util.Collections.unmodifiableMap(map);
    }
