    /**
     * Parse the AsciiDoc source input into a {@link Document} and convert it to the specified backend format.
     *
     * <p>If the to_file option is true, and the input is a file, the output is written to a file adjacent to the input
     * file, having an extension that corresponds to the backend format. Otherwise, if the to_file option is specified,
     * the file is written to that file. If to_file is not an absolute path, it is resolved relative to to_dir, if
     * given, otherwise the Document#base_dir. If the target directory does not exist, it will not be created unless the
     * mkdirs option is set to true. If the file cannot be written because the target directory does not exist, or
     * because it falls outside of the base_dir in safe mode, an exception is raised.
     *
     * <p>If the output is going to be written to a file, the header and footer are included unless specified otherwise
     * (writing to a file implies creating a standalone document). Otherwise, the header and footer are not included by
     * default and the converted result is returned.
     *
     * @param input the AsciiDoc source
     * @param options a Map of options to control processing (default: {})
     * @return the Document object if the converted String is written to a file, otherwise the converted String
     */
    public static Object convert(Object input, Map<String, Object> options) {
        Map<String, Object> convertOptions = options == null ? new LinkedHashMap<>() : new LinkedHashMap<>(options);
        // NOTE bind the logger for the whole conversion (including writing the output and copying the stylesheets)
        if (convertOptions.containsKey("logger")) {
            Logger logger = LoggerManager.resolveLoggerOption(convertOptions.get("logger"));
            convertOptions.put("logger", logger);
            return LoggerManager.callWithLogger(logger, () -> doConvert(input, convertOptions));
        }
        return doConvert(input, convertOptions);
    }

    private static Object doConvert(Object input, Map<String, Object> options) {
        options.remove("parse");
        Object toDir = options.remove("to_dir");
        boolean mkdirs = Boolean.TRUE.equals(options.remove("mkdirs"));
        Object toFile = options.remove("to_file");

        String siblingPath = null;
        Object writeToTarget = null;
        boolean streamOutput = false;
        if (toFile == null || Boolean.TRUE.equals(toFile)) {
            if ((writeToTarget = toDir) == null && input instanceof Path path) {
                siblingPath = Helpers.absolutePath(path);
            }
            toFile = null;
        } else if (Boolean.FALSE.equals(toFile)) {
            toFile = null;
        } else if ("/dev/null".equals(toFile)) {
            return load(input, options);
        } else if (toFile instanceof Appendable || toFile instanceof java.io.OutputStream) {
            streamOutput = true;
        } else {
            toFile = toFile.toString();
            options.put("to_file", toFile);
            writeToTarget = toFile;
        }

        if (!options.containsKey("standalone")) {
            if (siblingPath != null || writeToTarget != null) {
                options.put("standalone", options.getOrDefault("header_footer", true));
            } else if (options.containsKey("header_footer")) {
                options.put("standalone", options.get("header_footer"));
            }
        }

        String outdir = null;
        // NOTE outfile may be controlled by document attributes, so resolve outfile after loading
        if (siblingPath != null) {
            options.put("to_dir", outdir = Helpers.dirname(siblingPath));
        } else if (writeToTarget != null) {
            if (toDir != null) {
                if (toFile != null) {
                    options.put("to_dir", Helpers.dirname(Helpers.expandPath(toFile.toString(), toDir.toString())));
                } else {
                    options.put("to_dir", Helpers.expandPath(toDir.toString(), null));
                }
            } else if (toFile != null) {
                options.put("to_dir", Helpers.dirname(Helpers.expandPath(toFile.toString(), null)));
            }
        }

        // NOTE the to_dir option is always set when outputting to a file
        // NOTE the to_file option is only passed if assigned an explicit path
        Document doc = load(input, options);

        Object outfile;
        if (siblingPath != null) { // write to file in same directory
            outfile = Helpers.joinPath(outdir, doc.getAttributes().get("docname") + doc.getOutfilesuffix());
            if (outfile.equals(siblingPath)) {
                throw new AsciidoctorException("input file and output file cannot be the same: " + outfile);
            }
        } else if (writeToTarget != null) { // write to explicit file or directory
            String workingDir = options.containsKey("base_dir")
                    ? Helpers.expandPath(options.get("base_dir").toString(), null)
                    : Helpers.workingDirectory();
            // QUESTION should the jail be the working_dir or doc.base_dir???
            String jail = doc.getSafe() >= SafeMode.SAFE.getLevel() ? workingDir : null;
            Map<String, Object> resolveOpts = Map.of("target_name", "to_dir", "recover", false);
            String outfilePath = null;
            if (toDir != null) {
                outdir = doc.normalizeSystemPath(toDir.toString(), workingDir, jail, resolveOpts);
                if (toFile != null) {
                    outfilePath = doc.normalizeSystemPath(toFile.toString(), outdir, null, resolveOpts);
                    // reestablish outdir as the final target directory (in the case to_file had directory segments)
                    outdir = Helpers.dirname(outfilePath);
                } else {
                    outfilePath = Helpers.joinPath(outdir, doc.getAttributes().get("docname") + doc.getOutfilesuffix());
                }
            } else if (toFile != null) {
                outfilePath = doc.normalizeSystemPath(toFile.toString(), workingDir, jail, resolveOpts);
                // establish outdir as the final target directory (in the case to_file had directory segments)
                outdir = Helpers.dirname(outfilePath);
            }
            outfile = outfilePath;

            if (input instanceof Path path && outfile != null
                    && outfile.equals(Helpers.absolutePath(path))) {
                throw new AsciidoctorException("input file and output file cannot be the same: " + outfile);
            }

            if (mkdirs) {
                Helpers.mkdirP(outdir);
            } else if (!Helpers.isDirectory(outdir)) {
                // NOTE we intentionally refer to the directory as it was passed to the API
                throw new AsciidoctorException(
                        "target directory does not exist: " + toDir + " (hint: set :mkdirs option)");
            }
        } else { // write to stream
            outfile = toFile;
            outdir = null;
        }

        // NOTE the output is a String for a textual format, but it can be of any type (e.g., the bytes of a PDF document)
        Object output;
        if (outfile != null && !streamOutput) {
            Map<String, Object> convertOpts = new LinkedHashMap<>();
            convertOpts.put("outfile", outfile);
            convertOpts.put("outdir", outdir);
            output = doc.convertOutput(convertOpts);
        } else {
            output = doc.convertOutput(Map.of());
        }

        if (outfile == null) {
            return output;
        }

        doc.write(output, outfile);

        // NOTE document cannot control this behavior if safe >= SafeMode::SERVER
        // NOTE skip if stylesdir is a URI
        Object stylesdir = doc.getAttribute("stylesdir");
        if (!streamOutput && doc.getSafe() < SafeMode.SECURE.getLevel() && doc.hasAttribute("linkcss")
                && doc.hasAttribute("copycss") && doc.isBasebackend("html")
                && !(stylesdir != null && Helpers.isUriish(stylesdir.toString()))) {
            boolean copyAsciidoctorStylesheet = false;
            boolean copyUserStylesheet = false;
            String stylesheet = doc.getStringAttribute("stylesheet");
            if (stylesheet != null) {
                if (DEFAULT_STYLESHEET_KEYS.contains(stylesheet)) {
                    copyAsciidoctorStylesheet = true;
                } else if (!Helpers.isUriish(stylesheet)) {
                    copyUserStylesheet = true;
                }
            }
            SyntaxHighlighter syntaxHl = doc.getSyntaxHighlighter();
            boolean copySyntaxHlStylesheet = syntaxHl != null && syntaxHl.isWriteStylesheet(doc);
            if (copyAsciidoctorStylesheet || copyUserStylesheet || copySyntaxHlStylesheet) {
                String stylesoutdir = doc.normalizeSystemPath(Strings.valueOf(stylesdir), outdir,
                        doc.getSafe() >= SafeMode.SAFE.getLevel() ? outdir : null, Map.of());
                if (mkdirs) {
                    Helpers.mkdirP(stylesoutdir);
                } else if (!Helpers.isDirectory(stylesoutdir)) {
                    throw new AsciidoctorException("target stylesheet directory does not exist: " + stylesoutdir
                            + " (hint: set :mkdirs option)");
                }

                if (copyAsciidoctorStylesheet) {
                    Stylesheets.getInstance().writePrimaryStylesheet(stylesoutdir);
                    // FIXME should Stylesheets also handle the user stylesheet?
                } else if (copyUserStylesheet) {
                    Object stylesheetSrcVal = doc.getAttribute("copycss");
                    String stylesheetSrc;
                    if ("".equals(stylesheetSrcVal) || Boolean.TRUE.equals(stylesheetSrcVal)) {
                        stylesheetSrc = doc.normalizeSystemPath(stylesheet);
                    } else {
                        // NOTE in this case, copycss is a source location (but cannot be a URI)
                        stylesheetSrc = doc.normalizeSystemPath(String.valueOf(stylesheetSrcVal));
                    }
                    String stylesheetDest = doc.normalizeSystemPath(stylesheet, stylesoutdir,
                            doc.getSafe() >= SafeMode.SAFE.getLevel() ? outdir : null, Map.of());
                    // NOTE don't warn if src can't be read and dest already exists (see #2323)
                    if (!stylesheetSrc.equals(stylesheetDest)) {
                        Map<String, Object> readOpts = new LinkedHashMap<>();
                        readOpts.put("warn_on_failure", !Helpers.isFile(stylesheetDest));
                        readOpts.put("label", "stylesheet");
                        String stylesheetData = doc.readAsset(stylesheetSrc, readOpts);
                        if (stylesheetData != null) {
                            String stylesheetOutdir = Helpers.dirname(stylesheetDest);
                            if (!stylesheetOutdir.equals(stylesoutdir) && !Helpers.isDirectory(stylesheetOutdir)) {
                                if (!mkdirs) {
                                    throw new AsciidoctorException("target stylesheet directory does not exist: "
                                            + stylesheetOutdir + " (hint: set :mkdirs option)");
                                }
                                Helpers.mkdirP(stylesheetOutdir);
                            }
                            Helpers.writeFile(stylesheetDest, stylesheetData);
                        }
                    }
                }
                if (copySyntaxHlStylesheet) {
                    syntaxHl.writeStylesheet(doc, stylesoutdir);
                }
            }
        }
        return doc;
    }

