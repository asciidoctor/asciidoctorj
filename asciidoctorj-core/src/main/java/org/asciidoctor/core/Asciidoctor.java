/**
 * The main application interface (API) for Asciidoctor. This API provides methods to parse AsciiDoc content and
 * convert it to various output formats using built-in or third-party converters.
 *
 * <p>An AsciiDoc document can be as simple as a single line of content, though it more commonly starts with a document
 * header that declares the document title and document attribute definitions. The document header is then followed by
 * zero or more section titles, optionally nested, to organize the paragraphs, blocks, lists, etc. of the document.
 *
 * <p>By default, the processor converts the AsciiDoc document to HTML 5 using a built-in converter. However, this
 * behavior can be changed by specifying a different backend (e.g., docbook). A backend is a keyword for an output
 * format (e.g., DocBook). That keyword, in turn, is used to select a converter, which carries out the request to
 * convert the document to that format.
 *
 * <pre>{@code
 * // Convert an AsciiDoc file
 * Asciidoctor.convertFile("document.adoc", Map.of("safe", "safe"));
 *
 * // Convert an AsciiDoc string
 * String html = (String) Asciidoctor.convert("I'm using *Asciidoctor* version {asciidoctor-version}.",
 *     Map.of("safe", "safe"));
 *
 * // Parse an AsciiDoc file into a document object
 * Document doc = Asciidoctor.loadFile("document.adoc", Map.of("safe", "safe"));
 * }</pre>
 */
