package org.asciidoctor.extension;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.asciidoctor.Asciidoctor;
import org.asciidoctor.Options;
import org.asciidoctor.ast.Block;
import org.asciidoctor.ast.Document;
import org.asciidoctor.ast.Section;
import org.asciidoctor.ast.StructuralNode;
import org.jsoup.Jsoup;
import org.jsoup.select.Elements;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

public class WhenAnExtensionAppendsChildBlocksTest {

    private Asciidoctor asciidoctor = Asciidoctor.Factory.create();

    final String document = """
            = Test document

            == Section 1

            some text

            == Section 2

            more text

            """;

    @Test
    @DisplayName("should be able to blocks via Block_append")
    public void shouldBeAbleToBlocksViaBlockAppend() {

        // given:

        final String additionalText = "Text added by Treeprocessor";
        asciidoctor.javaExtensionRegistry().treeprocessor(new Treeprocessor() {

            int lastid = 0;

            @Override
            public Document process(Document document) {
                document.getBlocks().stream().filter(block -> block instanceof Section).forEach(
                    block -> {
                        Block newBlock = createBlock(block, "paragraph", additionalText, new HashMap<>());
                        newBlock.setId("NewBlock_" + lastid++);
                        block.append(newBlock);
                    });
                return document;
            }
        });

        // when:
        String result = asciidoctor.convert(this.document, Options.builder().standalone(false).build());

        // then:
        org.jsoup.nodes.Document htmlDocument = Jsoup.parse(result);
        assertThat(htmlDocument.select("#NewBlock_0")).isNotEmpty();
        assertThat(htmlDocument.select("#NewBlock_1")).isNotEmpty();
        assertThat(htmlDocument.select("#NewBlock_2")).isEmpty();

    }

    @Test
    @DisplayName("should be able to append and parse raw asciidoc content via Block_parse")
    public void shouldBeAbleToAppendAndParseRawAsciidocContentViaBlockParse() {

        // given:
        final String newContentClass = "newcontent";
        final List<String> contentToAdd = """

                [.%s]
                This is content added by an extension.

                [.%s]
                And this as well
                """.formatted(newContentClass, newContentClass).lines().toList();

        asciidoctor.javaExtensionRegistry().treeprocessor(new Treeprocessor() {
            @Override
            public Document process(Document document) {
                document.getBlocks().stream().filter(block -> block instanceof Section).forEach(
                    section -> parseContent(section, contentToAdd));
                return document;
            }
        });

        // when:
        String result = asciidoctor.convert(document, Options.builder().standalone(false).build());

        // then:
        org.jsoup.nodes.Document htmlDocument = Jsoup.parse(result);
        assertThat(htmlDocument.select(".sect1").stream().allMatch(
            section -> {
                Elements paragraphs = section.select(".paragraph");
                return !paragraphs.get(0).hasClass(newContentClass) &&
                        paragraphs.get(1).hasClass(newContentClass) &&
                        paragraphs.get(2).hasClass(newContentClass);
            })).isTrue();
    }

    @Test
    @DisplayName("should invoke block macro processor on additionally parsed content")
    public void shouldInvokeBlockMacroProcessorOnAdditionallyParsedContent() {

        // given:
        final List<String> contentToAdd = """

                testmacro::target[]
                """.lines().toList();

        final String expectedContent = "Generated by BlockMacro";

        asciidoctor.javaExtensionRegistry().treeprocessor(new Treeprocessor() {
            @Override
            public Document process(Document document) {
                document.getBlocks().stream().filter(block -> block instanceof Section).forEach(
                    block -> parseContent(block, contentToAdd));
                return document;
            }
        });

        asciidoctor.javaExtensionRegistry().blockMacro(new BlockMacroProcessor("testmacro") {
            @Override
            public StructuralNode process(StructuralNode parent, String target, Map<String, Object> attributes) {
                return createBlock(parent, "paragraph", expectedContent, new HashMap<>());
            }
        });

        // when:
        String result = asciidoctor.convert(document, Options.builder().standalone(false).build());

        // then:
        assertThat(result).contains(expectedContent);
    }
}
